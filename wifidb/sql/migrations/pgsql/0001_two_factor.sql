-- Two-factor sign-in (authenticator apps and passkeys), recovery codes and admin mode: lib/two_factor.inc.php

CREATE TABLE user_two_factor (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(255) NOT NULL,
  type varchar(10) NOT NULL,
  name varchar(100) NOT NULL,
  secret varchar(1024) NOT NULL,
  public_key text NULL,
  alg integer NULL,
  sign_count bigint NOT NULL DEFAULT 0,
  last_step bigint NOT NULL DEFAULT 0,
  created timestamp(0) NOT NULL,
  last_used timestamp(0) NULL
);
CREATE INDEX user_two_factor_username ON user_two_factor (username);

CREATE TABLE user_recovery_codes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(255) NOT NULL,
  code_hash varchar(255) NOT NULL,
  created timestamp(0) NOT NULL,
  used timestamp(0) NULL
);
CREATE INDEX user_recovery_codes_username ON user_recovery_codes (username);

CREATE TABLE two_factor_attempts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(255) NOT NULL,
  attempted timestamp(0) NOT NULL
);
CREATE INDEX two_factor_attempts_username_attempted ON two_factor_attempts (username, attempted);

ALTER TABLE user_info
  ADD COLUMN mfa_login smallint NOT NULL DEFAULT 1,
  ADD COLUMN mfa_prefs smallint NOT NULL DEFAULT 0;

ALTER TABLE user_login_hashes
  ADD COLUMN mfa_pending smallint NOT NULL DEFAULT 0,
  ADD COLUMN mfa_at timestamp(0) NULL,
  ADD COLUMN admin_until timestamp(0) NULL,
  ADD COLUMN challenge varchar(255) NULL,
  ADD COLUMN challenge_expires timestamp(0) NULL;
