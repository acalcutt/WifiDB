-- In-app notifications and who wants which ones: lib/notify.inc.php

CREATE TABLE notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(255) NOT NULL,
  type varchar(40) NOT NULL,
  title varchar(255) NOT NULL,
  body text NULL,
  link varchar(500) NULL,
  created timestamp(0) NOT NULL,
  read_at timestamp(0) NULL
);
CREATE INDEX notifications_username_read ON notifications (username, read_at);
CREATE INDEX notifications_created ON notifications (created);

CREATE TABLE notification_prefs (
  username varchar(255) NOT NULL,
  type varchar(40) NOT NULL,
  in_app smallint NOT NULL,
  PRIMARY KEY (username, type)
);
